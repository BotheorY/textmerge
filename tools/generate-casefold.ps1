# Rebuild the full, non-Turkic Unicode 17 case-fold table from the checked-in
# Unicode Character Database. No network is needed to regenerate this file.
$ErrorActionPreference = 'Stop'
$projectDirectory = Split-Path -Parent $PSScriptRoot
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// SPDX-License-Identifier: MIT AND Unicode-3.0')
$lines.Add('//! Generated by tools/generate-casefold.ps1 from Unicode 17.0.0.')
$lines.Add('//! Unicode data license: assets/UNICODE-LICENSE.txt. Do not edit the table.')
$lines.Add('pub fn fold(text: &str) -> String {')
$lines.Add('    let mut output = String::with_capacity(text.len());')
$lines.Add('    for character in text.chars() {')
$lines.Add('        if character.is_ascii() { output.push(character.to_ascii_lowercase()); continue; }')
$lines.Add('        match MAPPINGS.binary_search_by_key(&(character as u32), |entry| entry.0) {')
$lines.Add('            Ok(index) => output.push_str(MAPPINGS[index].1),')
$lines.Add('            Err(_) => output.push(character),')
$lines.Add('        }')
$lines.Add('    }')
$lines.Add('    output')
$lines.Add('}')
$lines.Add('const MAPPINGS: &[(u32, &str)] = &[')
foreach ($line in Get-Content -LiteralPath (Join-Path $projectDirectory 'assets\CaseFolding-17.0.0.txt')) {
    $data = ($line -split '#')[0].Trim()
    if (!$data) {continue}
    $parts = $data -split ';'
    $status = $parts[1].Trim()
    if ($status -notin @('C','F')) {continue}
    $codePoint = $parts[0].Trim()
    $mapping = (($parts[2].Trim() -split '\s+') | ForEach-Object {'\u{' + $_.ToLowerInvariant() + '}'}) -join ''
    $lines.Add('    (0x' + $codePoint + ', "' + $mapping + '"),')
}
$lines.Add('];')
[System.IO.File]::WriteAllLines((Join-Path $projectDirectory 'src\casefold.rs'),$lines,[System.Text.UTF8Encoding]::new($false))
